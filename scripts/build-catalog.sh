#!/usr/bin/env bash
# Generate catalog.json from tools/*/meta.json + per-platform tarball sha256s.
#
# Invoked from the release workflow AFTER all platform tarballs are built,
# downloaded, and re-chmodded. Can also be run locally for a file:// catalog
# pointing at a local tarball directory.
#
# Inputs:
#   --tarball-dir <DIR>      Directory containing per-platform tarballs named
#                            <tool>-<os>-<arch>.tar.gz. Required.
#   --version <VER>          Semver tag (e.g. 0.1.0 or 0.1.0-rc1). Required.
#   --url-template <TMPL>    Template with {name}, {version}, {os}, {arch}.
#                            Default: GH Releases URL for combycode/dpe-tools.
#   --output <FILE>          Where to write catalog.json. Default: stdout.
#
# Output: a single catalog.json on stdout (or --output) shaped per the
# runner's `Catalog` type.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"

TARBALL_DIR=""
VERSION=""
URL_TEMPLATE='https://github.com/combycode/dpe-tools/releases/download/v{version}/{name}-{os}-{arch}.tar.gz'
OUTPUT=""

while [ $# -gt 0 ]; do
    case "$1" in
        --tarball-dir)   TARBALL_DIR="$2"; shift 2 ;;
        --version)       VERSION="$2"; shift 2 ;;
        --url-template)  URL_TEMPLATE="$2"; shift 2 ;;
        --output)        OUTPUT="$2"; shift 2 ;;
        -h|--help)
            sed -n '2,18p' "$0"
            exit 0
            ;;
        *)
            echo "unknown arg: $1" >&2
            exit 2
            ;;
    esac
done

[ -n "$TARBALL_DIR" ] || { echo "--tarball-dir required" >&2; exit 2; }
[ -n "$VERSION" ]     || { echo "--version required"     >&2; exit 2; }
[ -d "$TARBALL_DIR" ] || { echo "tarball dir does not exist: $TARBALL_DIR" >&2; exit 2; }

# Sha helper: prefer sha256sum (Linux), fall back to shasum -a 256 (macOS).
sha256_of() {
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum "$1" | awk '{print $1}'
    elif command -v shasum >/dev/null 2>&1; then
        shasum -a 256 "$1" | awk '{print $1}'
    else
        echo "no sha256 tool available" >&2; exit 2
    fi
}

# Platforms we expect tarballs for. If a platform tarball is missing we skip
# its sha256 entry; runner will warn at install time on the missing platform.
PLATFORMS=(
    "linux-x64"
    "linux-arm64"
    "darwin-x64"
    "darwin-arm64"
    "windows-x64"
)

# Collect tools from tools/*/meta.json. jq is required for clean JSON building.
command -v jq >/dev/null 2>&1 || { echo "jq required" >&2; exit 2; }

TOOLS_JSON='{}'
for meta in "$ROOT"/tools/*/meta.json; do
    [ -f "$meta" ] || continue
    name=$(jq -r '.name'        "$meta")
    desc=$(jq -r '.description' "$meta")
    runtime=$(jq -r '.runtime'  "$meta")

    # Build per-platform sha map by hashing tarballs that exist.
    sha_map='{}'
    for plat in "${PLATFORMS[@]}"; do
        tar="$TARBALL_DIR/${name}-${plat}.tar.gz"
        if [ -f "$tar" ]; then
            sha=$(sha256_of "$tar")
            sha_map=$(jq --arg p "$plat" --arg s "$sha" '. + {($p): $s}' <<< "$sha_map")
        fi
    done

    entry=$(jq -n \
        --arg desc    "$desc" \
        --arg runtime "$runtime" \
        --arg ver     "$VERSION" \
        --arg name    "$name" \
        --arg url     "$URL_TEMPLATE" \
        --argjson sha "$sha_map" \
        '{
            description: $desc,
            runtime:     $runtime,
            version:     $ver,
            binary: {
                name:         $name,
                url_template: $url,
                sha256:       $sha
            }
        }')

    TOOLS_JSON=$(jq --arg n "$name" --argjson e "$entry" '. + {($n): $e}' <<< "$TOOLS_JSON")
done

UPDATED_AT=$(date -u +"%Y-%m-%dT%H:%M:%SZ")
CATALOG=$(jq -n \
    --arg ver      "$VERSION" \
    --arg updated  "$UPDATED_AT" \
    --argjson tools "$TOOLS_JSON" \
    '{
        version:    $ver,
        updated_at: $updated,
        comment:    "Generated by scripts/build-catalog.sh - do not hand-edit.",
        tools:      $tools
    }')

if [ -n "$OUTPUT" ]; then
    printf '%s\n' "$CATALOG" > "$OUTPUT"
    echo "wrote $OUTPUT"
else
    printf '%s\n' "$CATALOG"
fi
